function bulamuClampScore(value, fallback){
  var n = Number(value);
  if(!isFinite(n)) n = fallback === undefined ? 5 : fallback;
  return Math.max(0, Math.min(10, Math.round(n * 10) / 10));
}

function bulamuText(recipe){
  return [
    recipe.name || '',
    (recipe.tags || []).join(' '),
    (recipe.ingredients || []).join(' '),
    recipe.method || '',
    recipe.why || '',
    (recipe.tasteProfile || []).join(' '),
    (recipe.substitutions || []).join(' ')
  ].join(' ').toLowerCase();
}

function bulamuHasAny(text, terms){
  return terms.some(function(term){ return text.indexOf(term) > -1; });
}

function bulamuInferFlavourBase(recipe){
  var text = bulamuText(recipe);
  if(bulamuHasAny(text, ['tomato']) && bulamuHasAny(text, ['garlic','onion'])) return 'tomato-onion-garlic';
  if(bulamuHasAny(text, ['ginger']) && bulamuHasAny(text, ['garlic','lemon'])) return 'ginger-garlic-lemon';
  if(bulamuHasAny(text, ['groundnut','peanut'])) return 'measured groundnut sauce';
  if(bulamuHasAny(text, ['yogurt','curd'])) return 'cool yogurt creaminess';
  if(bulamuHasAny(text, ['lemon','lime','cucumber','salad'])) return 'fresh lemon-herb';
  if(bulamuHasAny(text, ['cumin','turmeric','curry','spiced'])) return 'mild spice base';
  if(bulamuHasAny(text, ['grill','grilled','roast','roasted','smoky'])) return 'grilled or roasted flavour';
  if(bulamuHasAny(text, ['pumpkin','soup','broth'])) return 'warming soup base';
  return 'simple savoury base';
}

function bulamuInferTexture(recipe){
  var text = bulamuText(recipe);
  var texture = [];
  if(bulamuHasAny(text, ['salad','cucumber','cabbage','crunchy','crisp'])) texture.push('crunchy');
  if(bulamuHasAny(text, ['yogurt','avocado','groundnut','creamy','smooth'])) texture.push('creamy');
  if(bulamuHasAny(text, ['soup','porridge','soft','stew','matooke','pumpkin'])) texture.push('soft');
  if(bulamuHasAny(text, ['grilled','roasted','maize'])) texture.push('roasted');
  if(!texture.length) texture.push('balanced');
  return texture;
}

function bulamuInferAroma(recipe){
  var text = bulamuText(recipe);
  var aroma = [];
  ['garlic','ginger','onion','tomato','lemon','mint','cumin','turmeric','curry','pepper','herbs'].forEach(function(term){
    if(text.indexOf(term) > -1) aroma.push(term);
  });
  if(!aroma.length && (recipe.tasteProfile || []).indexOf('savoury') > -1) aroma.push('savoury');
  return aroma;
}

function bulamuInferCulinary(recipe){
  var text = bulamuText(recipe);
  var taste = recipe.tasteProfile || [];
  var aroma = bulamuInferAroma(recipe);
  var deliciousBoost = 0;
  if(aroma.length >= 2) deliciousBoost += 1.2;
  if(taste.length >= 3) deliciousBoost += 1;
  if(bulamuHasAny(text, ['lemon','garlic','ginger','tomato','onion','mint','cumin','turmeric','groundnut','avocado'])) deliciousBoost += 1.1;
  if(bulamuHasAny(text, ['bland','plain'])) deliciousBoost -= 2.2;
  var baseIntensity = recipe.meal === 'snack' ? 6.5 : 7;
  var familyAcceptance = 7;
  if(bulamuHasAny(text, ['family','familiar','matooke','beans','egg','sweet potato','fish','chicken','yogurt','banana'])) familyAcceptance += 1.2;
  if(bulamuHasAny(text, ['premium','supermarket','quinoa','tofu'])) familyAcceptance -= 1;
  var repeatAppeal = familyAcceptance + (recipe.time <= 20 ? 0.6 : -0.4) + (recipe.substitutions && recipe.substitutions.length >= 2 ? 0.8 : 0);
  var inferred = {
    flavourBase: bulamuInferFlavourBase(recipe),
    texture: bulamuInferTexture(recipe),
    tasteIntensity: bulamuClampScore(baseIntensity + deliciousBoost, 7),
    sauce: bulamuInferFlavourBase(recipe),
    aroma: aroma,
    familyAcceptance: bulamuClampScore(familyAcceptance, 7),
    repeatAppeal: bulamuClampScore(repeatAppeal, 7),
    presentation: bulamuHasAny(text, ['salad','bowl','fruit','cucumber','tomato','avocado']) ? 'colourful plate or bowl' : 'home-style plate',
    deliciousnessNotes: 'Use aroma, acid, herbs, texture, and measured sauce to make the meal enjoyable without relying on excess salt, sugar, or oil.'
  };
  return Object.assign({}, inferred, recipe.culinary || {});
}

function bulamuInferPractical(recipe){
  var old = recipe.practicality || {};
  var cost = String(recipe.cost || '').toLowerCase();
  var market = String(old.marketAccess || '').toLowerCase();
  var equipment = old.equipment || 'stove';
  var equipmentList = Array.isArray(equipment) ? equipment : [equipment];
  var costScore = cost === 'low' ? 9 : cost === 'medium' ? 6.5 : cost === 'high' ? 3.5 : 6;
  var availability = market.indexOf('common') > -1 ? 9 : market.indexOf('regional') > -1 ? 7 : market.indexOf('supermarket') > -1 ? 5.5 : 7;
  var cookingSkill = recipe.time <= 10 ? 2 : recipe.time <= 20 ? 3 : recipe.time <= 35 ? 5 : 7;
  var prepBurden = recipe.time <= 15 ? 2.5 : recipe.time <= 30 ? 4.5 : 7;
  var inferred = {
    marketAvailability: bulamuClampScore(availability, 7),
    cookingSkill: bulamuClampScore(cookingSkill, 4),
    equipment: equipmentList,
    batchCook: Boolean(old.batchCook),
    lunchboxFriendly: recipe.meal === 'lunch' || bulamuHasAny(bulamuText(recipe), ['bowl','salad','boiled','roasted','portable']),
    costScore: bulamuClampScore(costScore, 7),
    prepBurden: bulamuClampScore(prepBurden, 4),
    localAvailability: availability >= 8 ? 'high' : availability >= 6 ? 'moderate' : 'limited'
  };
  return Object.assign({}, inferred, recipe.practical || {});
}

function bulamuInferFeedback(recipe){
  var inferred = {
    averageTasteRating: null,
    wouldEatAgainRate: null,
    repeatComplaints: 0,
    dislikedCount: 0,
    symptomComplaints: 0,
    expensiveComplaints: 0,
    hardToCookComplaints: 0,
    lastReviewedAt: null
  };
  return Object.assign({}, inferred, recipe.feedback || {});
}

function bulamuInferQuality(recipe){
  var culinary = recipe.culinary || bulamuInferCulinary(recipe);
  var practical = recipe.practical || bulamuInferPractical(recipe);
  var feedback = recipe.feedback || bulamuInferFeedback(recipe);
  var reviewBonus = recipe.reviewStatus === 'approved' ? 0.8 : recipe.reviewStatus === 'client-tested' ? 0.7 : recipe.reviewStatus === 'dietician-reviewed' ? 0.4 : recipe.reviewStatus === 'needs-dietician-review' ? -2 : 0;
  var clinicalBonus = recipe.reviewStatus === 'needs-dietician-review' ? -2 : 0.5;
  var flavourScore = bulamuClampScore(culinary.tasteIntensity, 7);
  var practicalityScore = bulamuClampScore((practical.marketAvailability + (10 - practical.cookingSkill) + practical.costScore + (10 - practical.prepBurden)) / 4, 7);
  var affordabilityScore = bulamuClampScore(practical.costScore, 7);
  var availabilityScore = bulamuClampScore(practical.marketAvailability, 7);
  var familyAcceptanceScore = bulamuClampScore(culinary.familyAcceptance, 7);
  var repeatAppealScore = bulamuClampScore(culinary.repeatAppeal - (feedback.repeatComplaints || 0) * 0.5 - (feedback.dislikedCount || 0) * 0.4, 7);
  var overallScore = bulamuClampScore(
    flavourScore * 0.26 +
    practicalityScore * 0.23 +
    affordabilityScore * 0.14 +
    availabilityScore * 0.13 +
    familyAcceptanceScore * 0.12 +
    repeatAppealScore * 0.12 +
    reviewBonus +
    clinicalBonus,
    7
  );
  var repeatRisk = repeatAppealScore >= 8 ? 'low' : repeatAppealScore >= 6 ? 'moderate' : 'high';
  var inferred = {
    flavourScore: flavourScore,
    practicalityScore: practicalityScore,
    affordabilityScore: affordabilityScore,
    availabilityScore: availabilityScore,
    familyAcceptanceScore: familyAcceptanceScore,
    repeatAppealScore: repeatAppealScore,
    overallScore: overallScore,
    repeatRisk: repeatRisk,
    recommendationTier: overallScore >= 8 ? 'default' : overallScore >= 6.5 ? 'use-with-variety' : 'use-selectively'
  };
  return Object.assign({}, inferred, recipe.quality || {});
}

function bulamuRecipe(base){
  var defaults = {
    tags: [],
    avoid: [],
    time: 20,
    cost: 'Low',
    ingredients: [],
    method: '',
    why: '',
    portion: '1 adult serving. Adjust up for athletes, teenagers, pregnancy, breastfeeding, or weight gain; adjust down for weight loss if hunger and energy remain stable.',
    tasteProfile: ['familiar','savoury'],
    suitability: {
      diabetes: 'moderate',
      hypertension: 'moderate',
      cholesterol: 'moderate',
      kidney: 'needs review',
      pregnancy: 'moderate',
      weightLoss: 'moderate',
      weightGain: 'moderate',
      child: 'moderate'
    },
    cautions: [],
    allergens: [],
    substitutions: [],
    nutrition: {energy:'moderate', protein:'moderate', fibre:'moderate', glycaemicLoad:'moderate', sodium:'low'},
    practicality: {budget:'medium', equipment:'stove', batchCook:false, marketAccess:'common'},
    culinary: null,
    practical: null,
    feedback: null,
    quality: null,
    reviewStatus: 'dietician-reviewed',
    clinicalReview: 'Rule-screened for common adult nutrition use; individual review still needed for pregnancy complications, CKD, diabetes medication, severe symptoms, or abnormal labs.',
    clinicalNote: ''
  };
  var recipe = Object.assign({}, defaults, base, {
    suitability: Object.assign({}, defaults.suitability, base.suitability || {}),
    nutrition: Object.assign({}, defaults.nutrition, base.nutrition || {}),
    practicality: Object.assign({}, defaults.practicality, base.practicality || {})
  });
  recipe.culinary = bulamuInferCulinary(recipe);
  recipe.practical = bulamuInferPractical(recipe);
  recipe.feedback = bulamuInferFeedback(recipe);
  recipe.quality = bulamuInferQuality(recipe);
  return recipe;
}

